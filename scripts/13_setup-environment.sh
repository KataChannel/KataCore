#!/usr/bin/env node

// 🔍 Environment Variables Validation Script
console.log('🔍 Validating environment configuration...\n');

const requiredVars = {
  development: [
    'DATABASE_URL',
    'JWT_SECRET',
    'NEXTAUTH_SECRET',
    'NEXTAUTH_URL'
  ],
  production: [
    'DATABASE_URL', 
    'JWT_SECRET',
    'NEXTAUTH_SECRET', 
    'NEXTAUTH_URL',
    'NODE_ENV'
  ]
};

const optionalVars = [
  'FACEBOOK_APP_ID',
  'FACEBOOK_APP_SECRET',
  'GOOGLE_CLIENT_ID',
  'GOOGLE_CLIENT_SECRET'
];

const performanceVars = [
  'NEXT_TELEMETRY_DISABLED',
  'NODE_OPTIONS',
  'PRISMA_QUERY_ENGINE_LIBRARY'
];

function validateEnvironment() {
  const env = process.env.NODE_ENV || 'development';
  const required = requiredVars[env] || requiredVars.development;
  
  console.log(`Environment: ${env.toUpperCase()}`);
  console.log('=' .repeat(40));
  
  // Check required variables
  console.log('\n📋 Required Variables:');
  let missingRequired = [];
  
  required.forEach(varName => {
    const value = process.env[varName];
    if (!value) {
      console.log(`❌ ${varName}: Missing`);
      missingRequired.push(varName);
    } else if (value.includes('REPLACE-WITH') || value.includes('your-')) {
      console.log(`⚠️  ${varName}: Needs configuration`);
    } else {
      console.log(`✅ ${varName}: Configured`);
    }
  });
  
  // Check optional variables
  console.log('\n🔧 Optional Variables:');
  optionalVars.forEach(varName => {
    const value = process.env[varName];
    if (!value) {
      console.log(`⏸️  ${varName}: Not set`);
    } else if (value.includes('your-')) {
      console.log(`⚠️  ${varName}: Needs configuration`);  
    } else {
      console.log(`✅ ${varName}: Configured`);
    }
  });
  
  // Check performance variables
  console.log('\n🚀 Performance Variables:');
  performanceVars.forEach(varName => {
    const value = process.env[varName];
    if (value) {
      console.log(`✅ ${varName}: ${value}`);
    } else {
      console.log(`⏸️  ${varName}: Not set`);
    }
  });
  
  // Summary
  console.log('\n' + '=' .repeat(40));
  if (missingRequired.length > 0) {
    console.log(`❌ Missing ${missingRequired.length} required variable(s)`);
    console.log('Please configure:', missingRequired.join(', '));
    process.exit(1);
  } else {
    console.log('✅ All required variables are configured');
    console.log('🚀 Environment is ready!');
  }
}

validateEnvironment();
EOF

chmod +x validate-env.js
success "Created environment validation script"

