# 🔧 Environment Setup Guide

## Quick Start

1. **Automatic Setup** (Recommended):
   ```bash
   ./setup-environment.sh
   ```

2. **Manual Setup**:
   - Copy `.env.local` and update values
   - Run `node validate-env.js` to check configuration

## Environment Files

### Development (`.env.local`)
- Auto-generated with optimized defaults
- Update database URL and auth secrets
- Ready for local development

### Production (`.env.production`)
- Use `.env.production.template` as starting point
- Generate secure secrets (64+ characters)
- Update all "REPLACE-WITH" and "your-" values

## Validation

Run environment validation:
```bash
node validate-env.js
```

## Required Updates

### 1. Database URL
```bash
DATABASE_URL="postgresql://username:password@localhost:5432/tazagroup_dev"
```

### 2. JWT Secrets
Generate secure secrets:
```bash
# Generate random secret
openssl rand -base64 64

# Or use Node.js
node -e "console.log(require('crypto').randomBytes(64).toString('base64'))"
```

### 3. Facebook Auth (Optional)
- Get credentials from [Facebook Developers](https://developers.facebook.com/)
- Update `FACEBOOK_APP_ID` and `FACEBOOK_APP_SECRET`

## Performance Variables

These are automatically set for optimization:
- `NEXT_TELEMETRY_DISABLED=1` - Faster startup
- `NODE_OPTIONS=--max-old-space-size=2048` - Memory optimization
- `PRISMA_QUERY_ENGINE_LIBRARY=1` - Faster database queries

## Security Notes

⚠️ **Important**:
- Never commit `.env.local` or `.env.production` to version control
- Use different secrets for development and production
- Regularly rotate production secrets
- Use HTTPS in production (`SECURE_COOKIES=true`)

## Troubleshooting

### Database Connection Issues
1. Check if PostgreSQL is running
2. Verify database URL format
3. Test connection: `npm run test:db`

### Build Issues
1. Run `node validate-env.js`
2. Check for missing required variables
3. Ensure NODE_OPTIONS are set correctly

### Performance Issues
1. Verify `NEXT_TELEMETRY_DISABLED=1`
2. Check Node.js memory settings
3. Enable performance monitoring in production
EOF

